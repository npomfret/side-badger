function notOffered(row: {
  id: string;
  status: 'planned' | 'not-offered';
  capability: string;
  evidence: string[];
  copy: string;
}): FeatureRecord {
  return {
    id: row.id,
    homePage: null,
    capability: row.capability,
    problem: '',
    audiences: { primary: [], secondary: [] },
    status: row.status,
    confidence: 'medium',
    evidence: row.evidence,
    verifiedAt: APP_COMMIT,
    limits: [`What copy may say: ${row.copy}`],
    prerequisites: [],
    proof: [],
    relatedFeatures: [],
    useCases: [],
    searchLanguage: [],
    claims: [],
    notApproved: [],
    release: 2,
  };
}

