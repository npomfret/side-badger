import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { load } from 'cheerio';
import TurndownService from 'turndown';
import { gfm } from 'turndown-plugin-gfm';

/** Derive an alternate representation from the actual rendered page, never a second copy. */
export function renderMarkdown(html, { url, locale, indexable }) {
  const $ = load(html);
  const main = $('main').first();
  if (main.length !== 1 || main.find('h1').length !== 1) {
    throw new Error(`Markdown needs a main landmark and one h1: ${url}`);
  }
  main.find('script, style, template, svg, [aria-hidden="true"], [hidden], nav, button, input, select, textarea').remove();
  // These link markers repeat the destination type; other screen-reader text is meaningful content.
  main.find('a.launch-cta > .sr-only, .compare-source > a > .sr-only').remove();
  // The homepage's simulated app screens are illustrations, not the visitor's account data.
  // Keep the use-case descriptions and links that share its visual slot.
  main.find('.scene__visual').not(':has(.world__text)').remove();
  main.find('.world__table, .worlds__controls').remove();
  // Definition lists carry real computed balances. Preserve each name/amount association.
  main.find('dt').each((_, element) => {
    const term = $(element);
    term.append(': ');
  });
  main.find('dd').each((_, element) => $(element).append('<br>'));
  main.find('[href], [src]').each((_, element) => {
    for (const attr of ['href', 'src']) {
      const value = $(element).attr(attr);
      if (value) $(element).attr(attr, new URL(value, url).href);
    }
  });

  const converter = new TurndownService({ headingStyle: 'atx', codeBlockStyle: 'fenced', bulletListMarker: '-' });
  converter.use(gfm);
  const metadata = {
    title: $('title').text(),
    description: $('meta[name="description"]').attr('content') ?? '',
    url,
    lang: $('html').attr('lang') ?? locale,
    robots: indexable ? 'index, follow' : 'noindex',
  };
  const frontmatter = Object.entries(metadata).map(([key, value]) => `${key}: ${JSON.stringify(value)}`).join('\n');
  return `---\n${frontmatter}\n---\n\n${converter.turndown(main.html() ?? '')}\n`;
}

/** Metadata for nginx lives outside the document root. Explicit .md URLs are alternates. */
export function markdownHeaders(pages) {
  const canonical = pages.map(page => `    "${page.markdownPath}" '<${page.url}>; rel="canonical"';`).join('\n');
  const noindex = pages.filter(page => !page.indexable).map(page => `    "${page.markdownPath}" noindex;`).join('\n');
  return `# Generated by the Astro Markdown integration; do not serve this file publicly.
map $uri $side_badger_markdown_canonical {
    default "";
${canonical}
}
map $uri $side_badger_markdown_noindex {
    default "";
${noindex}
}
map $request_uri $side_badger_markdown_robots {
    default $side_badger_markdown_noindex;
    ~^/[^?]*index\\.md(?:\\?|$) noindex;
}
`;
}

/** resolvePage is supplied by Astro's registry-aware config (including publication checks). */
export function markdownSite({ resolvePage }) {
  return {
    name: 'side-badger-markdown',
    hooks: {
      'astro:build:done': async ({ dir, pages, logger }) => {
        const root = fileURLToPath(dir);
        const generated = [];
        for (const page of pages) {
          const path = `/${page.pathname}`.replace(/\/+$/, '/') || '/';
          const info = resolvePage(path);
          if (!info) continue;
          const htmlFile = join(root, path.slice(1), 'index.html');
          const html = await readFile(htmlFile, 'utf8');
          const markdownPath = new URL('index.md', info.url).pathname;
          await writeFile(join(root, markdownPath.slice(1)), renderMarkdown(html, info));
          generated.push({ ...info, markdownPath });
        }
        const nginxDir = new URL('../../.astro/', import.meta.url);
        await mkdir(nginxDir, { recursive: true });
        await writeFile(new URL('markdown-headers.conf', nginxDir), markdownHeaders(generated));
        logger.info(`Generated ${generated.length} Markdown representations.`);
      },
    },
  };
}
