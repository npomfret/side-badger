import { writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

// nginx has no numeric comparison in map. Normalize the RFC's three decimal places,
// then compare each digit at the first differing position. No runtime JS module needed.
export function negotiationConfig() {
  const lines = ['# Generated by node scripts/markdown/nginx.mjs. Do not edit by hand.',
    '# Explicit text/markdown wins ties; absent/wildcard-only requests stay HTML.',
    '# Repeated identical media ranges use their first occurrence. Malformed q means zero.'];
  for (const [name, range, fallback] of [
    ['any', '\\*/\\*', '""'],
    ['text', 'text/\\*', '$side_badger_accept_any'],
    ['html', 'text/html', '$side_badger_accept_text'],
    ['markdown', 'text/markdown', '""'],
  ]) {
    lines.push(`map $http_accept $side_badger_accept_${name} {`,
      `    default ${fallback};`,
      `    "~*(?:^|,)[ \\t]*${range}[ \\t]*(?<sb_${name}_params>;[^,]*)?(?:,|$)" "present$sb_${name}_params";`, '}');
  }
  for (const name of ['html', 'markdown']) {
    const variable = `$side_badger_${name}_quality`;
    lines.push(`map $side_badger_accept_${name} ${variable} {`,
      '    default 1000;', '    "" 0000;',
      '    "~*;[ \\t]*q[ \\t]*=[ \\t]*1(?:\\.0{0,3})?[ \\t]*(?:;|$)" 1000;',
      '    "~*;[ \\t]*q[ \\t]*=[ \\t]*0\\.?[ \\t]*(?:;|$)" 0000;');
    for (const digits of [3, 2, 1]) {
      lines.push(`    "~*;[ \\t]*q[ \\t]*=[ \\t]*0\\.(?<sb_${name}_q${digits}>[0-9]{${digits}})[ \\t]*(?:;|$)" "0\${sb_${name}_q${digits}}${'0'.repeat(3 - digits)}";`);
    }
    lines.push('    "~*;[ \\t]*q[ \\t]*=" 0000;', '}');
  }
  lines.push('map "$side_badger_markdown_quality:$side_badger_html_quality" $side_badger_wants_markdown {',
    '    default 0;', '    ~^0000: 0;', '    "~^([0-9]{4}):\\1$" 1;');
  for (let position = 0; position < 4; position++) {
    for (let digit = 1; digit <= 9; digit++) {
      const prefix = position ? `([0-9]{${position}})` : '';
      const same = position ? '\\1' : '';
      const tail = `[0-9]{${3 - position}}`;
      lines.push(`    "~^${prefix}${digit}${tail}:${same}[0-${digit - 1}]${tail}$" 1;`);
    }
  }
  lines.push('}', 'map "$uri:$side_badger_wants_markdown" $side_badger_markdown_candidate {',
    '    default "";',
    '    "~^(?<sb_markdown_page>/.*/|/):1$" "${sb_markdown_page}index.md";', '}', '');
  return lines.join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await writeFile(new URL('../../nginx/markdown-negotiation.conf', import.meta.url), negotiationConfig());
}
